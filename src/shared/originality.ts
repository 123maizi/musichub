/**
 * 从一个字段里切出「同一实体的多个写法」。
 *
 * 输入可能是「周杰伦 (Jay Chou)」「周杰伦/Jay Chou」「周杰伦、费玉清」，
 * 这里把括号内的拉丁名与各种分隔符切开，逐个归一化后返回。
 */
export function aliasTokens(text: string): string[] {
  if (!text) return []
  const out = new Set<string>()
  // 主名
  const main = normalizeName(text)
  if (main) out.add(main)
  // 括号里的拉丁名（「周杰伦 (Jay Chou)」）
  for (const m of text.matchAll(/[（(【\[｛{]([^）)】\]｝}]{1,40})[）)】\]｝}]/g)) {
    const inner = normalizeName(m[1])
    if (inner) out.add(inner)
  }
  // 分隔符切分（「周杰伦、费玉清」「A / B」「A feat. B」）
  for (const part of text.split(/[/、,，;；|&+]|\sfeat\.?\s|\sft\.?\s/i)) {
    const p = normalizeName(part)
    if (p) out.add(p)
  }
  // 别名归一
  const mapped = new Set<string>()
  for (const t of out) mapped.add(ARTIST_ALIAS[t] ?? t)
  return [...mapped].filter(Boolean)
}

/**
 * 关键词切成片段。
 *
 * 「周杰伦 晴天」→ ['周杰伦','晴天']；「周杰伦-晴天」→ 同样。
 * 用户不会按分词规范输入，所以按空白与常见分隔符切，够用。
 */
export function keywordTokens(keyword: string): string[] {
  if (!keyword) return []
  return keyword
    .split(/[\s\-–—_/、,，;；|+.]+/)
    .map((t) => normalizeName(t))
    .filter((t) => t.length > 0)
}

