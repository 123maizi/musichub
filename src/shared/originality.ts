const TRAD_SIMP = new Map(TRAD_SIMP_PAIRS)

/** 把繁体字转成简体（只做表内覆盖的字，其余原样保留） */
export function toSimplified(text: string): string {
  if (!text) return ''
  let out = ''
  for (const ch of text) out += TRAD_SIMP.get(ch) ?? ch
  return out
}

/**
 * 归一化任意名字：小写、去掉括号内容、只留中日韩文字与字母数字、繁转简。
 *
 * 去掉括号是为了处理「周杰伦 (Jay Chou)」这类写法 —— 括号里通常是补充说明，
 * 不参与主名匹配；同时把括号里的拉丁名单独保留为「别名候选」，见 aliasTokens。
 */
export function normalizeName(text: string): string {
  if (!text) return ''
  const simplified = toSimplified(text)
  return simplified
    .toLowerCase()
    .replace(/[（(【\[｛{〔〈<「『《].*?[）)】\]｝}〕〉>」』》]/g, '')
    .replace(/[^\u4e00-\u9fff\u3400-\u4dbfa-z0-9]+/g, '')
    .trim()
}

