/**
 * 原唱优先排序
 *
 * 背景：搜「晴天」，前排常被 DJ 版、翻唱、伴奏淹没。已有的「歌名纯净度」
 * （见 purity.ts）只能治一半 —— 因为 **DJ 版也可以把歌名写成《晴天》**。
 *
 * 真正难伪装的是**歌手字段**：原唱那条的歌手通常就是干净的本名，
 * 而改版往往是「DJ 某某」「某某某（Cover）」。所以这里的核心是
 * **歌手精确匹配 + 归一化**，歌名纯净度只作为辅助项。
 *
 * 原来的实现有一个致命缺陷：拿**整个关键词**去 `singer.includes(kw)`。
 * 用户搜「周杰伦 晴天」时，歌名和歌手字段都不含这一整串，两边都匹配不上，
 * 等于什么信号都没用上。这里先把关键词拆成片段，再逐片段比对。
 */

